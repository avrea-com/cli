"""Generate Go documentation metadata from the pinned Python snapshot.

Baseline upgrades are explicit: update BASELINE in compare_auth, regenerate the
metadata and command inventory, then run the parity matrix. Working-tree Python
edits do not change this migration input or freeze Python development.
"""

from pathlib import Path
from scripts.compare_auth import BASELINE
import argparse
import io
import json
import os
import subprocess
import sys
import tarfile
import tempfile


def generate():
    root = Path(__file__).resolve().parents[1]
    archive = subprocess.check_output(["git", "archive", BASELINE, "avrea_cli"], cwd=root)
    with tempfile.TemporaryDirectory(prefix="avr-doc-oracle-") as directory:
        with tarfile.open(fileobj=io.BytesIO(archive)) as source:
            source.extractall(directory, filter="data")
        code = (
            "import json; from avrea_cli.docs_gen import build_tree; "
            "from scripts.go_help_metadata import terminal_tree; "
            "tree=build_tree(); tree['terminal']=terminal_tree(); "
            "print(json.dumps(tree, indent=2, ensure_ascii=False, default=str))"
        )
        return subprocess.check_output(
            [sys.executable, "-c", code],
            cwd=directory,
            env=os.environ | {"PYTHONPATH": os.pathsep.join([directory, str(root)]), "PYTHONIOENCODING": "utf-8"},
            text=True,
            encoding="utf-8",
        )


def object_entries(source, start=0):
    """Yield JSON object value spans in character offsets, without textual search."""
    decoder = json.JSONDecoder()
    position = start + 1
    while True:
        while source[position].isspace() or source[position] == ",":
            position += 1
        if source[position] == "}":
            return
        key, position = decoder.raw_decode(source, position)
        while source[position].isspace():
            position += 1
        if source[position] != ":":
            raise ValueError("Expected JSON object separator")
        position += 1
        while source[position].isspace():
            position += 1
        begin = position
        _, position = decoder.raw_decode(source, position)
        yield key, begin, position


def help_index(source):
    """Index each command's help directly into the embedded UTF-8 metadata."""
    terminal = next(begin for name, begin, _ in object_entries(source) if name == "terminal")
    lines = [
        "// Code generated by scripts.generate_go_doc_metadata; DO NOT EDIT.",
        "",
        "package docgen",
        "",
        "// Offsets address metadata.json bytes; no full-tree parsing is needed for help.",
        "func helpTemplateJSON(path string) []byte {",
        "\tswitch path {",
    ]
    for name, begin, end in object_entries(source, terminal):
        start_byte = len(source[:begin].encode("utf-8"))
        end_byte = start_byte + len(source[begin:end].encode("utf-8"))
        lines += [f"\tcase {json.dumps(name, ensure_ascii=False)}:", f"\t\treturn metadata[{start_byte}:{end_byte}]"]
    lines += ["\t}", "\treturn nil", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    value = generate()
    for target, content in (
        (Path("docgen/metadata.json"), value),
        (Path("docgen/help_index.go"), help_index(value)),
    ):
        if args.check:
            if target.read_text(encoding="utf-8") != content:
                raise SystemExit(f"{target} differs from the pinned Python input")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
